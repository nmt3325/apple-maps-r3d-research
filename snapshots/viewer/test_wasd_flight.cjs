const {chromium}=require('playwright-core');
(async()=>{
 const b=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox','--disable-dev-shm-usage','--enable-unsafe-swiftshader']});
 const p=await b.newPage({viewport:{width:1360,height:840}});
 p.on('pageerror',e=>console.log('PAGEERROR',e.message));
 p.on('console',m=>{if(m.type()==='error')console.log('JSERROR',m.text().slice(0,500))});
 await p.goto('http://127.0.0.1:8891/',{waitUntil:'domcontentloaded'});
 await p.waitForFunction(()=>window.__flyDebug?.c3mCache?.size>=21,{},{timeout:80000});
 const snapshot=()=>p.evaluate(()=>({pos:window.__flyDebug.camera.position.toArray(),quaternion:window.__flyDebug.camera.quaternion.toArray(),fly:window.__flyDebug.flyMode,orbitEnabled:window.__flyDebug.ctrl.enabled,hud:!document.getElementById('flyHud').hidden}));
 const start=await snapshot();
 await p.locator('#flyMode').click();
 const on=await snapshot();
 if(!on.fly||on.orbitEnabled||!on.hud)throw new Error('Fly mode activation failed: '+JSON.stringify(on));
 await p.keyboard.down('w');await p.waitForTimeout(650);await p.keyboard.up('w');const forward=await snapshot();
 await p.keyboard.down('e');await p.waitForTimeout(520);await p.keyboard.up('e');const up=await snapshot();
 await p.keyboard.down('q');await p.waitForTimeout(520);await p.keyboard.up('q');const down=await snapshot();
 await p.keyboard.down('d');await p.waitForTimeout(500);await p.keyboard.up('d');const strafe=await snapshot();
 const dist=(a,b)=>Math.hypot(a[0]-b[0],a[1]-b[1],a[2]-b[2]);
 console.log('forward',dist(on.pos,forward.pos),'delta y',forward.pos[1]-on.pos[1]);
 console.log('E rise',up.pos[1]-forward.pos[1],'Q descend',down.pos[1]-up.pos[1]);
 console.log('D strafe',dist(down.pos,strafe.pos));
 if(!(dist(on.pos,forward.pos)>12))throw new Error('W movement failed');
 if(!(up.pos[1]-forward.pos[1]>10))throw new Error('E ascend failed');
 if(!(down.pos[1]-up.pos[1]<-10))throw new Error('Q descend failed');
 if(!(dist(down.pos,strafe.pos)>10))throw new Error('D movement failed');
 const canvas=await p.locator('#view canvas').boundingBox();
 await p.mouse.click(canvas.x+canvas.width/2,canvas.y+canvas.height/2);
 await p.waitForTimeout(300);
 const locked=await p.evaluate(()=>document.pointerLockElement===window.__flyDebug.renderer.domElement);
 const prior=await snapshot();
 await p.mouse.move(canvas.x+canvas.width/2+105,canvas.y+canvas.height/2-65,{steps:2});
 await p.waitForTimeout(300);
 const looked=await snapshot();
 console.log('mouse pointerLocked',locked,'changed orientation',dist(prior.quaternion,looked.quaternion));
 await p.keyboard.press('Escape');await p.keyboard.press('f');const off=await snapshot();
 console.log('OFF',off,'start',start.pos);
 if(off.fly||!off.orbitEnabled||off.hud)throw new Error('Orbit mode restoration failed');
 await p.screenshot({path:'/tmp/apple-flyover-wasd-flight-test.png'});
 await b.close();
 console.log('PASS WASD + up + down + strafing + mode restore');
})().catch(e=>{console.log('FAILED',e.stack);process.exit(1)});
